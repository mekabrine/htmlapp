import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('HTMLAppV3/HTMLAppBridgeLint.swift','utf8');
const adapter = source.match(/<script data-htmlapp-vision-fixer>([\s\S]*?)<\/script>/)[1];
let calls = 0, release;
const context = vm.createContext({Date, Error, Math, document:{createElement:()=>({getContext:()=>({drawImage(){}}),toDataURL:()=> 'data:image/jpeg;base64,test'})},
  HTMLAppNative:{vision:{detectFaces:async()=>{calls++; await new Promise(r=>release=r);return {faces:[{x:.1,y:.2,width:.3,height:.4}]};}}}});
vm.runInContext(adapter,context);
const detector = vm.runInContext('new FaceDetector()',context);
const first = detector.detect({width:100,height:200});
const concurrent = detector.detect({width:100,height:200});
assert.equal(calls,1); release();
const faces = await first; await concurrent;
assert.equal(faces[0].boundingBox.x,10);
assert.ok(Math.abs(faces[0].boundingBox.y-80)<.001);
assert.equal(faces[0].boundingBox.width,30);
assert.equal(faces[0].landmarks.length,0);
await detector.detect({width:100,height:200}); assert.equal(calls,1,'bounded cached sampling');
assert.equal((await vm.runInContext('new FaceDetector()',context).detect({width:0,height:0})).length,0);
const denied = vm.createContext({Date, Error, Math, document:context.document,HTMLAppNative:{vision:{detectFaces:async()=>{throw new Error('permission denied')}}}});
vm.runInContext(adapter,denied);
await assert.rejects(()=>vm.runInContext('new FaceDetector()',denied).detect({width:10,height:10}),/permission denied/);
const preserved = vm.createContext({FaceDetector:class Existing{}});
vm.runInContext(adapter,preserved); assert.equal(preserved.FaceDetector.name,'Existing');

const kit = fs.readFileSync('HTMLApp/Resources/RuntimeLibraries/htmlapp/controls.js','utf8').replaceAll('export function','function');
